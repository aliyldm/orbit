'use strict';
const currentAfter=require('./helpers/installed-main').after;
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),dir=path.join(root,'decompiled/assembly-bootstrap-diagnostics'),read=p=>fs.readFileSync(path.join(dir,p),'utf8');
test('actual native failure instrumentation preserves behavior and reports only bounded localhost diagnostics',()=>{
 const proof=JSON.parse(read('evidence.json'));
 const correction=JSON.parse(fs.readFileSync(path.join(root,'decompiled/assembly-null-traits-patch/evidence.json'),'utf8'));
 assert.equal(correction.beforeSha256,proof.afterSha256);
 const droneToggle=JSON.parse(fs.readFileSync(path.join(root,'decompiled/drone-master-toggle-patch/evidence.json'),'utf8'));
 assert.equal(droneToggle.beforeSha256,correction.afterSha256);
 const bulk=JSON.parse(fs.readFileSync(path.join(root,'decompiled/upgrade-bulk-patch/evidence.json'),'utf8'));assert.equal(bulk.beforeSha256,droneToggle.afterSha256);
 assert.equal(currentAfter(bulk.afterSha256),crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'client/spacemap/main.swf'))).digest('hex'));
 assert.equal(proof.nonAbcIdentical,true);assert.equal(proof.unchangedNonAbcTags,256);assert.equal(proof.changes.length,1);
 const ui=read('verified/scripts/net/bigpoint/darkorbit/fui/UISystem.as');
 assert.match(ui,/_localDiagnosticCount >= 40/);assert.match(ui,/http:\/\/127\.0\.0\.1:8095\/client\/do_img\/global\/items\/resource\/upgrade-module_30x30\.png\?flashdiag=/);
 assert.match(ui,/detail\.substr\(0,1800\)/);assert.match(ui,/IOErrorEvent\.IO_ERROR/);assert.match(ui,/SecurityErrorEvent\.SECURITY_ERROR/);
 assert.match(ui,/localFlashDiag\("ui-error"[\s\S]*?throw error;/);
 const command=read('verified/scripts/net/bigpoint/darkorbit/net/netty/CommandHandler.as');
 assert.match(command,/UISystem\.localFlashDiag\("command-error"/);assert.match(command,/EventStreamClient\.track\("flash.error"/);
 const inventory=read('verified/scripts/net/bigpoint/darkorbit/net/netty/handlers/items/UserInventoryHandler.as');
 assert.ok(inventory.indexOf('localFlashDiag("inventory-ready"')>inventory.indexOf('inventory.dispatchItemChanged();'));
});
