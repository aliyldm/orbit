using System.Security.Cryptography;
using System.Text.Json.Nodes;
using DarkOrbit.Server.Storage;
using Npgsql;
using StackExchange.Redis;

internal static class StorageVerification
{
    public static async Task Run()
    {
        int assertions = 0;
        void Check(bool condition, string message) { assertions++; if (!condition) throw new InvalidOperationException(message); }
        string pg = Environment.GetEnvironmentVariable("DARKORBIT_POSTGRES") ?? throw new InvalidOperationException("DARKORBIT_POSTGRES is required");
        var builder = new NpgsqlConnectionStringBuilder(pg);
        if (builder.Database != "darkorbit_development" || builder.Port != 55432 || builder.Host != "127.0.0.1") throw new InvalidOperationException("Integration tests only permit the isolated development database");
        await using var source = NpgsqlDataSource.Create(pg);
        string okSchema = "legacy_" + Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(8));
        string failedSchema = "legacy_" + Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(8));
        string privateDirectory = Path.GetFullPath("artifacts/private"); Directory.CreateDirectory(privateDirectory);
        string fixturePath = Path.Combine(privateDirectory, "storage-fixture-" + Guid.NewGuid().ToString("N") + ".json");
        var table = JsonNode.Parse("""
        {"name":"fixture","sql":"test-only source metadata","columns":[{"name":"id","type":"INTEGER"},{"name":"fractional","type":"INTEGER"},{"name":"text","type":"TEXT"},{"name":"bytes","type":"BLOB"}],"foreignKeys":[],"indexes":[],"rows":[[{"kind":"integer","value":"9007199254740993"},{"kind":"real","value":"0.125"},{"kind":"text","value":"Türkçe 🚀"},{"kind":"blob","value":"AAEC/w=="}],[{"kind":"integer","value":"2"},{"kind":"integer","value":"3"},{"kind":"null"},{"kind":"null"}]]}
        """)!;
        var fixture = new JsonObject { ["format"] = 1, ["tables"] = new JsonArray(table) };
        try
        {
            await File.WriteAllTextAsync(fixturePath, fixture.ToJsonString());
            await SnapshotImporter.Import(source, fixturePath, okSchema);
            await using (var cmd = source.CreateCommand($"SELECT id,fractional FROM \"{okSchema}\".fixture ORDER BY id DESC LIMIT 1"))
            await using (var reader = await cmd.ExecuteReaderAsync())
            {
                Check(await reader.ReadAsync(), "Imported row available");
                Check(reader.GetInt64(0) == 9007199254740993L && reader.GetDecimal(1) == 0.125M, "64bit IDs/fractional values preserved");
            }
            bool replay = false; try { await SnapshotImporter.Import(source, fixturePath, okSchema); } catch (PostgresException e) when (e.SqlState == "42P06") { replay = true; }
            Check(replay, "Existing archive cannot be overwritten");
            var bad = table.DeepClone(); bad["name"] = "invalid_tail"; bad["rows"]![0]![0]!["kind"] = "text";
            fixture["tables"]!.AsArray().Add(bad); await File.WriteAllTextAsync(fixturePath, fixture.ToJsonString());
            bool rejected = false; try { await SnapshotImporter.Import(source, fixturePath, failedSchema); } catch (InvalidDataException) { rejected = true; }
            Check(rejected, "Invalid tail rejects whole import");
            await using (var cmd = source.CreateCommand("SELECT count(*) FROM pg_namespace WHERE nspname=$1"))
            {
                cmd.Parameters.AddWithValue(failedSchema); Check((long)(await cmd.ExecuteScalarAsync())! == 0, "Failed archive rolled back including first table");
            }
            await using (var cmd = source.CreateCommand($"SELECT count(*) FROM \"{okSchema}\".fixture"))
                Check((long)(await cmd.ExecuteScalarAsync())! == 2, "Original successful archive unchanged after replay/failure");
        }
        finally
        {
            // Only the two random schemas generated by this test are eligible.
            foreach (string schema in new[] { okSchema, failedSchema })
            { await using var cmd = source.CreateCommand($"DROP SCHEMA IF EXISTS \"{schema}\" CASCADE"); await cmd.ExecuteNonQueryAsync(); }
            File.Delete(fixturePath);
        }
        Console.WriteLine("PASS PostgreSQL: exact 64bit/fraction/text/blob/null, replay guard and all-or-nothing rollback");

        string redisConnection = Environment.GetEnvironmentVariable("DARKORBIT_REDIS") ?? throw new InvalidOperationException("DARKORBIT_REDIS is required");
        var options = ConfigurationOptions.Parse(redisConnection); options.AbortOnConnectFail = true;
        if (options.EndPoints.Count != 1 || options.EndPoints[0].ToString() != "127.0.0.1:56379") throw new InvalidOperationException("Redis tests only permit isolated development endpoint");
        using var first = await ConnectionMultiplexer.ConnectAsync(options); using var second = await ConnectionMultiplexer.ConnectAsync(options);
        string prefix = "darkorbit-verify-" + Guid.NewGuid().ToString("N");
        var sessions = new RedisSessions(first, prefix); var remote = new RedisSessions(second, prefix);
        string token = await sessions.Issue(new(10, 1, 1)); string shortToken = await sessions.Issue(new(10, 1, 1), TimeSpan.FromMilliseconds(20));
        try
        {
            Check(await remote.Verify(token, 1, 1) == new SessionTicket(10, 1, 1), "Session visible to another process connection");
            Check(await remote.Verify(token, 2, 1) is null && await remote.Verify(token, 1, 2) is null, "Ticket bound to player and server");
            Check(await remote.Verify("invalid", 1, 1) is null, "Invalid token rejected");
            await Task.Delay(100); Check(await remote.Verify(shortToken, 1, 1) is null, "Ticket TTL enforced");
            var old = await sessions.Acquire(1, 1, TimeSpan.FromSeconds(30));
            var current = await remote.Acquire(1, 1, TimeSpan.FromSeconds(30));
            Check(current.Fence > old.Fence, "Replacement increments fencing token");
            Check(!await sessions.Release(1, 1, old), "Stale close cannot remove replacement");
            Check(!await sessions.Renew(1, 1, old, TimeSpan.FromSeconds(30)), "Stale connection cannot renew");
            Check(await remote.Renew(1, 1, current, TimeSpan.FromSeconds(30)), "Current owner can renew");
            Check(await remote.Release(1, 1, current), "Current owner can close");
            var claims = await Task.WhenAll(Enumerable.Range(0, 50).Select(_ => remote.Acquire(1, 1, TimeSpan.FromSeconds(30))));
            Check(claims.Select(c => c.Fence).Distinct().Count() == 50, "Concurrent claims have unique fences");
            var last = claims.MaxBy(c => c.Fence)!;
            foreach (var stale in claims.Where(c => c != last)) Check(!await sessions.Release(1, 1, stale), "Concurrent old claim cannot release winner");
            Check(await sessions.Release(1, 1, last), "Concurrent final claim remains active");
            await sessions.Revoke(token); Check(await remote.Verify(token, 1, 1) is null, "Revocation visible across connections");
        }
        finally
        {
            await sessions.Revoke(token); await sessions.Revoke(shortToken);
            await first.GetDatabase().KeyDeleteAsync(new RedisKey[] { $"{prefix}:{{1:1}}:connection", $"{prefix}:{{1:1}}:fence" });
        }
        Console.WriteLine("PASS Redis: cross-connection tickets, TTL/revocation, player/server binding, atomic fenced ownership and stale-close protection");
        Console.WriteLine(System.Text.Json.JsonSerializer.Serialize(new { status = "PASS", storageAssertions = assertions, fixturesCleaned = true }));
    }
}
